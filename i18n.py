def detect_language():
    """Language from the environment; English if it cannot tell."""
    for var in ('THREADEYES_LANG', 'LC_ALL', 'LC_MESSAGES', 'LANG'):
        v = os.environ.get(var, '')
        if v[:2].lower() in LANGS:
            return v[:2].lower()
    try:
        loc = locale.getlocale()[0] or ''
    except (ValueError, TypeError):
        loc = ''
    if loc[:2].lower() in LANGS:
        return loc[:2].lower()
    if loc.lower().startswith('spanish'):  # Windows names, e.g. "Spanish_Spain"
        return 'es'
    return 'en'


def texts(lang):
    return TEXTS[lang if lang in TEXTS else 'en']
